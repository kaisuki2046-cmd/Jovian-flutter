const pillar = (position, ganZhi) => ({ kind: 'pillar', position, ganZhi });

function rule(id, required, topic, basis, reading, limit, reference) {
  return {
    method: 'bazi', id: 'review-bazi-' + id, tradition: '子平八字 · 现代释义',
    input: { required, mustBeAbsent: [] },
    output: { topic, rule: basis, reading, limit }, source: reference,
  };
}

