import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const referenceSystems = ['bazi', 'ziwei', 'western'];

function readReference(directory, system) {
  const path = join(directory, `synastry-knowledge-base-${system}.json`);
  const data = JSON.parse(readFileSync(path, 'utf8').replace(/^\uFEFF/u, ''));
  if (data.manifest?.schemaVersion !== 2 || data.manifest.system !== system) {
    throw new Error(`Expected schema v2 for ${system}.`);
  }
  return data;
}

function merge(records, key) {
  const unique = new Map();
  for (const record of records) {
    const id = record[key];
    if (typeof id !== 'string' || !id) throw new Error(`Missing ${key}.`);
    if (unique.has(id) && JSON.stringify(unique.get(id)) !== JSON.stringify(record)) {
      throw new Error(`Conflicting ${key}: ${id}.`);
    }
    unique.set(id, record);
  }
  return [...unique.values()];
}

export function buildMethodDiagnostics(references) {
  const methods = merge(references.flatMap(({ methodLibrary }) => methodLibrary.methods), 'methodId')
    .map(({ methodId, system, name, procedure, expectedOutputs, limitations, sourceRefs, missingFactTypes, releaseStatus, locator }) =>
      ({ methodId, system, name, procedure, expectedOutputs, limitations, sourceRefs, missingFactTypes, releaseStatus, locator }));
  const byFactType = merge(references.flatMap(({ factMethodAdaptation }) => factMethodAdaptation.byFactType), 'factTypeId')
    .map(({ factTypeId, methodRefs }) => ({ factTypeId, methodRefs }));

  const sourceIds = new Set(references.flatMap(({ sources }) => sources.map(({ sourceId }) => sourceId)));
  for (const { methodId, sourceRefs } of methods) {
    if (sourceRefs.some((id) => !sourceIds.has(id))) throw new Error(`Missing method source in ${methodId}.`);
  }
  const methodIds = new Set(methods.map(({ methodId }) => methodId));
  for (const { methodRefs, factTypeId } of byFactType) {
    if (methodRefs.some((id) => !methodIds.has(id))) throw new Error(`Missing method in ${factTypeId}.`);
  }
  return { methodLibrary: { methods }, factMethodAdaptation: { byFactType } };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [directory] = process.argv.slice(2);
  if (!directory) throw new Error('Provide the directory containing the three synastry knowledge JSON files.');

  const diagnostics = buildMethodDiagnostics(referenceSystems.map((system) => readReference(directory, system)));
  const code = '// Generated by server/pack-reference-knowledge.mjs.\n'
    + "import type { MethodLibrary } from './method-library';\n\n"
    + `export const methodLibrary: MethodLibrary = ${JSON.stringify(diagnostics, null, 2)};\n`;
  writeFileSync(new URL('../model/method-diagnostics.ts', import.meta.url), code);
  console.log(JSON.stringify({ methods: diagnostics.methodLibrary.methods.length,
    factMappings: diagnostics.factMethodAdaptation.byFactType.length }));
}
