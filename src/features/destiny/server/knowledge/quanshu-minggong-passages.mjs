const birthStem = stem => ({ kind: 'natal_year_stem', stem });
const birthBranch = branch => ({ kind: 'natal_year_branch', branch });
const branches = '子丑寅卯辰巳午未申酉戌亥';

function passageInputs(spec, star, palace) {
  if (!star && !spec.anchorChange && !spec.sameAny?.length) {
    throw new Error('Reviewed Minggong passage requires a natal star or transformation.');
  }
  const placement = star => ({ kind: 'palace_star', palace, star, scope: 'origin' });
  const sector = star => ({ kind: 'palace_sector_star', palace, star });
  const trine = star => ({ kind: 'palace_trine_star', palace, star });
  const sectorChange = change => ({ kind: 'palace_sector_mutagen', palace, change });
  const opposite = ziweiRelativePalaces[(ziweiRelativePalaces.indexOf(palace) + 6) % ziweiRelativePalaces.length];
  const oppositePlacement = star => ({ kind: 'palace_star', palace: opposite, star, scope: 'origin' });
  const required = [
    ...(star ? [placement(star)] : []), ...(spec.same ?? []).map(placement), ...(spec.sector ?? []).map(sector),
    ...(spec.trine ?? []).map(trine),
    ...(spec.scope === 'body' || palace !== life ? [{ kind: 'palace_confirmed_body_seat', palace }] : []),
    ...(spec.gender ? [{ kind: 'natal_gender', gender: spec.gender }] : []),
    ...(spec.brightness ? [{ kind: 'palace_brightness', palace, star, brightness: spec.brightness, scope: 'origin' }] : []),
    ...((spec.opposite?.length || spec.oppositeAny?.length) ? [
      { kind: 'palace_relation', anchor: palace, target: opposite, relation: 'opposite' },
      ...(spec.opposite ?? []).map(oppositePlacement),
    ] : []),
    ...(spec.change ? [{ kind: 'star_mutagen', star, palace, change: spec.change, scope: 'origin' }] : []),
    ...(spec.sectorChanges ?? []).map(sectorChange),
    // The derived sector fact checks the unique natal carrier and its observed palace.
    ...(spec.anchorChange ? [{ kind: 'palace_mutagen', palace, change: spec.anchorChange, scope: 'origin' },
      sectorChange(spec.anchorChange)] : []),
    ...(spec.birthBranch ? [birthBranch(spec.birthBranch)] : []),
    ...(spec.noSixMalefics ? [{ kind: 'palace_sector_six_malefic_count', palace, count: 0 }] : []),
    ...(spec.lifeTrinesWithoutChanges ? [{ kind: 'palace_life_trines_without_auspicious_mutagens' }] : []),
  ];
  // Alternatives within each list are interchangeable. Different lists are required together.
  const choices = [
    [...(spec.stems ?? '')].map(birthStem), [...(spec.birthBranches ?? '')].map(birthBranch),
    (spec.sameAny ?? []).map(placement), (spec.sectorAny ?? []).map(sector), (spec.trineAny ?? []).map(trine),
    (spec.oppositeAny ?? []).map(oppositePlacement),
    (spec.sectorMaleficCounts ?? []).map(count => ({ kind: 'palace_sector_malefic_count', palace, count })),
    (spec.sectorBeneficCounts ?? []).map(count => ({ kind: 'palace_sector_benefic_count', palace, count })),
  ].filter(group => group.length);
  const anyOf = choices.length ? choices.reduce((groups, alternatives) =>
    groups.flatMap(group => alternatives.map(fact => [...group, fact])), [[]]) : [];
  return [...(spec.seats ?? [null])].map(branch => {
    const brightness = branch && palace === life && quanshuMinggongBrightness(star, branch);
    let exactTrine = [];
    if (spec.trineAt) {
      const [relatedStar, relatedBranch] = spec.trineAt;
      const offset = (branches.indexOf(branch) - branches.indexOf(relatedBranch) + 12) % 12;
      if (!branch || (offset !== 4 && offset !== 8)) throw new Error('Expected an exact Minggong trine branch.');
      const target = ziweiRelativePalaces[(ziweiRelativePalaces.indexOf(palace) + offset) % ziweiRelativePalaces.length];
      exactTrine = [
        { kind: 'palace_relation', anchor: palace, target, relation: 'trine' },
        { kind: 'palace_branch', palace: target, branch: relatedBranch },
        { kind: 'palace_star', palace: target, star: relatedStar, scope: 'origin' },
      ];
    }
    return normalizeRuleInput('ziwei', {
      required: [
        ...required, ...exactTrine,
        ...(branch ? [{ kind: 'palace_branch', palace, branch }] : []),
        ...(brightness ? [{ kind: 'palace_source_brightness', palace, star, branch, brightness, scope: 'origin',
          profile: quanshuMinggongProfile }] : []),
      ],
      mustBeAbsent: (spec.sectorAbsent ?? []).map(sector),
      anyOf,
    });
  });
}

export function compileQuanshuMinggongPassage(claim) {
  if (!claim.id.startsWith(prefix)) return undefined;
  const spec = passages[claim.id.slice(prefix.length)];
  if (!spec) return undefined;
  const { source, conditions, evidence } = claim;
  const digest = createHash('sha256').update(JSON.stringify({ source, conditions, evidence })).digest('hex');
  const sections = spec.passages ?? [spec];
  if (digest !== spec.hash || sections.some(({ text }) => text && !evidence.original_text.includes(text))) {
    return { reason: 'source_review_required', reviewNote: '所据卷二命宫表或歌诀发生变化，须重新对校原文和条件。' };
  }
  const star = spec.star ?? quanshuMinggongStar(claim);
  const anchors = spec.scope ? bodySeats : [life];
  if (!spec.text && !spec.passages) {
    return { compiler: quanshuMinggongPassageProfile, inputs: anchors.flatMap(palace => passageInputs(spec, star, palace)) };
  }
  return {
    reason: 'unmapped_condition', condition: '按《紫微斗数全书》卷二命宫表或歌诀的已核分句匹配',
    branches: sections.map(section => ({
      text: section.text, conditionCompiler: quanshuMinggongPassageProfile,
      inputs: anchors.flatMap(palace => passageInputs({ ...spec, ...section }, star, palace)),
    })),
  };
}
