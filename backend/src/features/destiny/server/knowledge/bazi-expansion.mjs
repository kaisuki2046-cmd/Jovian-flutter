function source(volume, section, passage) {
  const chapter = { 3: '三', 5: '五', 6: '六' }[volume];
  return {
    ...sanming, id: 'sanming-tonghui-v' + volume, edition: '维基文库卷' + chapter + '转录',
    passageId: 'sanming-coverage-v' + volume + '-' + passage,
    locator: '卷' + chapter + ' · ' + section,
    url: 'https://zh.wikisource.org/wiki/三命通會/卷' + chapter,
  };
}

const stemRole = (position, tenGod) => ({ kind: 'stem_ten_god', position, tenGod });
