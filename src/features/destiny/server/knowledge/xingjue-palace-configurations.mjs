export function xingjuePalaceConfigurationChapter(id) {
  const [, volume, chapter] = id.match(/^ziwei-v([123])-xingjue-(\d{3})-/u) ?? [];
  return chapters.get(`${volume}-${chapter}`);
}

export function compileXingjuePalaceConfiguration(claim) {
  if (!claim.id.startsWith('ziwei-v')) return undefined;
  const spec = reviewed.get(claim.id.replace(chapterId, ''));
  if (!spec) return undefined;
  const chapter = xingjuePalaceConfigurationChapter(claim.id);
  const [hash, ...passages] = spec;
  const { source, conditions, evidence } = claim;
  const fingerprint = createHash('sha256').update(JSON.stringify({ source, conditions, evidence })).digest('hex');
  if (fingerprint !== hash || passages.some(([text]) => !evidence.original_text.includes(text))) {
    return { reason: 'source_review_required', reviewNote: '《紫微星诀》' + chapter + '篇的原文、出处或条件有变化，须重新核对。' };
  }
  return {
    reason: 'unmapped_condition',
    condition: '按《紫微星诀》' + chapter + '篇已核的本命盘面分句匹配',
    branches: passages.map(([text, groups]) => ({
      text,
      conditionCompiler: xingjuePalaceConfigurationProfile,
      inputs: groups.map(group => normalizeRuleInput('ziwei', Array.isArray(group) ? { required: group } : group)),
    })),
  };
}
