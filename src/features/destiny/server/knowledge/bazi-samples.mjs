function monthFacts(month) {
  if (month.length === 2 && '甲乙丙丁戊己庚辛壬癸'.includes(month[0])) {
    return [{ kind: 'pillar', position: 'month', ganZhi: month }];
  }
  return [...month].map((branch) => ({ kind: 'branch', position: 'month', branch }));
}

