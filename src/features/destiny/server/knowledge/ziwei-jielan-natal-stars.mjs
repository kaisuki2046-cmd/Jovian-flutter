export function compileJielanNatalStars(claim) {
  if (!claim.id.includes('-jielan-')) return undefined;
  const key = claim.id.slice(6);
  const taiweiSuffix = key.startsWith(taiweiPrefix) ? key.slice(taiweiPrefix.length) : null;
  const taiyinSuffix = key.startsWith(taiyinPrefix) ? key.slice(taiyinPrefix.length) : null;
  const spec = taiweiSuffix === null
    ? reviewed.get(key) ?? taiyinPassages.get(taiyinSuffix) ?? starChapterFollowups.get(key)
      ?? laterStarChapters.get(key) ?? horseAndMutagenChapters.get(key) ?? maleficStarChapters.get(key)
      ?? additionalStarsAndExamples.get(key) ?? lateVolumeFive.get(key)
    : taiweiPassages.get(taiweiSuffix);
  if (!spec) return undefined;
  const [expected, ...passages] = spec;
  const { source, conditions, evidence } = claim;
  const digest = createHash('sha256').update(JSON.stringify({ source, conditions, evidence })).digest('hex');
  if (digest !== expected || passages.some(([text]) => text && !evidence.original_text.includes(text))) {
    return { reason: 'source_review_required', reviewNote: '《紫微斗数捷览》分星或三方加会的出处、原文或条件有变化，须重新核对。' };
  }
  const branches = passages.map(([text, groups]) => ({
    text,
    conditionCompiler: jielanNatalStarProfile,
    inputs: groups.map(group => normalizeRuleInput('ziwei', group)),
  }));
  return branches[0].text === null
    ? { compiler: jielanNatalStarProfile, inputs: branches[0].inputs,
      ...((reviewedStarSubcases.has(key) || key === 'v4-jielan-169-p001-001' || ['003', '006', '017', '032', '033'].includes(taiweiSuffix)
        || ['002', '004', '005', '008', '012', '014', '015', '017', '018', '019', '021', '023', '025'].includes(taiyinSuffix))
        && { remainingAlternatives: 1 }) }
    : { reason: 'unmapped_condition', condition: '按《紫微斗数捷览》已核分句取材', branches };
}
