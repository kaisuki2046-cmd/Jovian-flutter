export function compileQtbjSeasonalPassages(claim, compileLiteral) {
  if (!claim.id.startsWith('qtbj-')) return undefined;
  const spec = reviewed.get(claim.id.slice(5));
  if (!spec) return undefined;
  const [hash, anchor, ...passages] = spec;
  const { source, conditions, evidence } = claim;
  const digest = createHash('sha256').update(JSON.stringify({ source, conditions, evidence })).digest('hex');
  if (digest !== hash || passages.some(([text]) => text && !evidence.original_text.includes(text))) {
    return { reason: 'source_review_required', reviewNote: '《穷通宝鉴》本条月令、透藏或分句所据原文已变，须重新核对。' };
  }
  const branches = passages.map(([text, condition]) => ({
    text, conditionCompiler: qtbjSeasonalPassageProfile,
    inputs: compileLiteral(claim, { normalized: [anchor, condition] })?.inputs,
  }));
  const unresolved = branches.findIndex(branch => !branch.inputs?.length);
  if (unresolved !== -1) return { reason: 'source_review_required', reviewNote: '本条分句无法形成相容的四柱条件，须复核。', condition: passages[unresolved][1] };
  if (branches[0].text === null) return { compiler: qtbjSeasonalPassageProfile, inputs: branches[0].inputs };
  return { reason: conditions.excluded.length ? 'unmapped_exclusions' : 'unmapped_condition',
    condition: '按《穷通宝鉴》已核月令、透藏及分句取材', branches };
}
